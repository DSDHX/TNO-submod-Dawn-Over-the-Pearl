"""Build the five ending cabinets from the author's archived Chinese text."""
from __future__ import annotations

import struct
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/sources/DOP_GNG_cabinet_source.txt"
SLOTS = ("head_of_government", "foreign_minister", "economy_minister", "security_minister")
TITLES = ("政务司司长", "外务司司长", "财政司司长", "广东警务处处长")
# Source heading, route, focus tree, leader, four ministers in source order.
PROFILES = (
    ("索长", "lee", "dop_sonyjapan_ending1_lee_tree", "GNG_morita_akio",
     ("GNG_li_kashing", "DOP_GNG_yamashita_toshihiko", "GNG_stanley_ho", "GNG_omori_kan")),
    ("索富", "ibuka", "dop_sonyjapan_ending2_ibuka_tree", "GNG_morita_akio",
     ("GNG_ibuka_masaru", "DOP_GNG_yamashita_toshihiko", "DOP_GNG_idei_nobuyuki", "GNG_omori_kan")),
    ("财界", "finance", "dop_sonyjapan_ending3_hitachi_tree", "GNG_morita_akio",
     ("DOP_GNG_yamashita_toshihiko", "DOP_GNG_mita_katsushige", "DOP_GNG_ho_sin_hang", "GNG_omori_kan")),
    ("1962", "1962", "dop_sonyjapan_ending4_return1962_tree", "DOP_GNG_inaba_hidezo",
     ("DOP_GNG_idei_nobuyuki", "DOP_GNG_mita_katsushige", "DOP_GNG_yamashita_toshihiko", "GNG_omori_kan")),
    ("军管", "military", "dop_sonyjapan_ending5_second_roit_tree", "DOP_GNG_tamura_hideaki",
     ("GNG_omori_kan", "DOP_GNG_yamashita_toshihiko", "DOP_GNG_idei_nobuyuki", "GNG_tsuchida_kuniyasu")),
)
NAMES = {
    "GNG_morita_akio": "盛田昭夫", "GNG_li_kashing": "李嘉诚",
    "GNG_ibuka_masaru": "井深大", "GNG_stanley_ho": "何鸿燊",
    "GNG_omori_kan": "大森宽", "GNG_tsuchida_kuniyasu": "土田国保",
    "DOP_GNG_yamashita_toshihiko": "山下俊彦", "DOP_GNG_mita_katsushige": "三田胜茂",
    "DOP_GNG_ho_sin_hang": "何善衡", "DOP_GNG_idei_nobuyuki": "出井伸之",
    "DOP_GNG_inaba_hidezo": "稻叶秀三", "DOP_GNG_tamura_hideaki": "田村秀昭",
}
# Keep the existing TNO ministers' established traits. New offices only get
# their required slot marker; the source does not specify numerical bonuses.
EXISTING_TRAITS = {
    ("GNG_li_kashing", "head_of_government"): "hog_the_co_custodian",
    ("GNG_ibuka_masaru", "head_of_government"): "hog_second_among_equals",
    ("GNG_stanley_ho", "economy_minister"): "eco_man_of_many_talents",
    ("GNG_omori_kan", "security_minister"): "sec_a_wind_of_change",
    ("GNG_tsuchida_kuniyasu", "security_minister"): "sec_the_immovable_mountain",
}
PORTRAITS = {
    "DOP_GNG_yamashita_toshihiko": "Yamashita_Toshihiko",
    "DOP_GNG_mita_katsushige": "Mita_Katsushige",
    "DOP_GNG_ho_sin_hang": "Ho_Sin_Hang",
    "DOP_GNG_idei_nobuyuki": "Idei_Nobuyuki",
}


def source_entries() -> dict[tuple[str, str], str]:
    entries: dict[tuple[str, str], list[str]] = {}
    heading = person = None
    for raw in SOURCE.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line or line == "内阁文本":
            continue
        if line in {p[0] for p in PROFILES}:
            heading, person = line, None
        elif line in NAMES.values():
            if heading is None or (heading, line) in entries:
                raise ValueError(f"Unexpected or repeated person: {line}")
            person = line
            entries[(heading, person)] = []
        else:
            if heading is None or person is None:
                raise ValueError(f"Unassigned source text: {line}")
            entries[(heading, person)].append(line)
    expected = {(h, NAMES[c]) for h, _, _, leader, ministers in PROFILES for c in (leader, *ministers)}
    if set(entries) != expected or any(not body for body in entries.values()):
        raise ValueError("The source must contain exactly five complete cabinets / 25 biographies")
    return {key: "\n\n".join(body) for key, body in entries.items()}


def loc_line(key: str, value: str) -> str:
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f' {key}:0 "{value}"'


def write(relative: str, text: str, bom: bool = False) -> None:
    path = ROOT / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8-sig" if bom else "utf-8")


def build_text() -> None:
    entries = source_entries()
    loc = ["l_simp_chinese:"]
    effects = ["# Generated by tools/import_dop_cabinet.py; biographies are in docs/sources/.", ""]
    for heading, route, _, leader, ministers in PROFILES:
        effects += [f"DOP_GNG_apply_cabinet_{route} = {{", "\thidden_effect = {",
                    "\t\tif = {", f"\t\t\tlimit = {{ NOT = {{ has_country_flag = DOP_GNG_cabinet_{route} }} }}",
                    "\t\t\tremove_all_ministers = yes"]
        for character in (leader, *ministers):
            effects += ["\t\t\tif = {",
                        f"\t\t\t\tlimit = {{ NOT = {{ has_character = {character} }} }}",
                        f"\t\t\t\trecruit_character = {character}", "\t\t\t}"]
        if leader == "GNG_morita_akio":
            effects += ["\t\t\tpromote_character = GNG_morita_akio",
                        "\t\t\tset_politics = { ruling_party = paternalism }"]
        else:
            effects += [f"\t\t\tpromote_character = {leader}",
                        "\t\t\tset_politics = { ruling_party = despotism }"]
        desc = f"DOP_GNG_cabinet_{route}_leader_desc"
        effects += [f'\t\t\tset_country_leader_description = {{ desc = "{desc}" }}']
        loc += [loc_line(desc, entries[(heading, NAMES[leader])])]
        for character, slot, title in zip(ministers, SLOTS, TITLES):
            short = character.removeprefix("DOP_GNG_").removeprefix("GNG_")
            token = f"DOP_GNG_cabinet_{route}_{short}_{slot}"
            effects += [f"\t\t\t{character} = {{"]
            if character in PORTRAITS:
                sprite = f"GFX_DOP_GNG_minister_{PORTRAITS[character]}"
                effects += [f'\t\t\t\tset_portraits = {{ civilian = {{ small = "{sprite}" }} }}']
            traits = " ".join(filter(None, (slot, EXISTING_TRAITS.get((character, slot)))))
            effects += ["\t\t\t\tif = {", f"\t\t\t\t\tlimit = {{ has_advisor_role = {slot} }}",
                        f"\t\t\t\t\tremove_advisor_role = {{ slot = {slot} }}", "\t\t\t\t}",
                        "\t\t\t\tadd_advisor_role = {", "\t\t\t\t\tadvisor = {",
                        f"\t\t\t\t\t\tslot = {slot}", f"\t\t\t\t\t\tidea_token = {token}",
                        "\t\t\t\t\t\tallowed = { original_tag = GNG }",
                        f"\t\t\t\t\t\ttraits = {{ {traits} }}", "\t\t\t\t\t\tledger = civilian",
                        "\t\t\t\t\t\tcost = -1", "\t\t\t\t\t\tcan_be_fired = no",
                        "\t\t\t\t\t\tai_will_do = { factor = 0 }", "\t\t\t\t\t}",
                        "\t\t\t\t\tactivate = yes", "\t\t\t\t}", "\t\t\t}"]
            loc += [loc_line(token, NAMES[character]),
                    loc_line(token + "_desc", f"§Y{title}§!\n------------\n§L{entries[(heading, NAMES[character])]}§!")]
        effects += [f"\t\t\tclr_country_flag = DOP_GNG_cabinet_{p[1]}" for p in PROFILES]
        effects += [f"\t\t\tset_country_flag = DOP_GNG_cabinet_{route}",
                    f'\t\t\tlog = "[GetDateText]: [Root.GetName]: DOP cabinet installed: {route}"',
                    "\t\t}", "\t}", "}", ""]
    # A guarded daily hook also covers old saves and the existing tree-loading
    # debug decisions. Tree order is exclusive; cabinet flags prevent rehiring.
    effects += ["DOP_GNG_sync_cabinet = {"]
    for i, (_, route, tree, _, _) in enumerate(PROFILES):
        effects += [f"\t{'if' if i == 0 else 'else_if'} = {{",
                    f"\t\tlimit = {{ has_focus_tree = {tree} }}",
                    f"\t\tDOP_GNG_apply_cabinet_{route} = yes", "\t}"]
    effects += ["}"]
    write("common/scripted_effects/DOP_GNG_cabinet_effects.txt", "\n".join(effects))
    write("localisation/simp_chinese/DOP_GNG_cabinet_l_simp_chinese.yml", "\n".join(loc), bom=True)


def build_portraits() -> None:
    sprites = ["spriteTypes = {"]
    for stem in PORTRAITS.values():
        source = ROOT / f"gfx/leaders/GNG/DOP_{stem}.png"
        relative = f"gfx/interface/ideas/ministers/GNG/DOP_{stem}.dds"
        target = ROOT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(source) as portrait:
            # Keep proportions, include the head and upper torso, match TNO's
            # 65 x 67 minister sprites. No changes to the original portraits.
            scaled = ImageOps.contain(portrait.convert("RGBA"), (65, 67), Image.Resampling.LANCZOS)
            small = Image.new("RGBA", (65, 67), (0, 0, 0, 0))
            small.paste(scaled, ((65 - scaled.width) // 2, 0))
            small.save(target, pixel_format="DXT5")
        data = bytearray(target.read_bytes())
        struct.pack_into("<I", data, 8, 0x2100F)
        struct.pack_into("<I", data, 24, 1)
        struct.pack_into("<I", data, 28, 1)
        target.write_bytes(data)
        sprites += ["\tspriteType = {", f'\t\tname = "GFX_DOP_GNG_minister_{stem}"',
                    f'\t\ttexturefile = "{relative}"', "\t}"]
    sprites += ["}"]
    write("interface/DOP_GNG_cabinet.gfx", "\n".join(sprites))


if __name__ == "__main__":
    build_text()
    build_portraits()
    print("Built 5 cabinets, 25 source biographies, 20 advisor roles and 4 minister portraits.")
